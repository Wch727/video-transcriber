def build_ui(window) -> None:
    root = QWidget()
    window.setCentralWidget(root)
    outer = QHBoxLayout(root)
    outer.setContentsMargins(0, 0, 0, 0)
    outer.setSpacing(0)

    sidebar = QFrame()
    sidebar.setObjectName("sidebar")
    sidebar.setFixedWidth(304)
    outer.addWidget(sidebar)
    side = QVBoxLayout(sidebar)
    side.setContentsMargins(20, 24, 20, 16)
    side.setSpacing(12)
    brand = QHBoxLayout()
    window.title_label = QLabel()
    window.title_label.setObjectName("appTitle")
    brand.addWidget(window.title_label, 1)
    window.lang_toggle = QPushButton()
    window.lang_toggle.setFixedWidth(48)
    window.lang_toggle.clicked.connect(window._toggle_language)
    brand.addWidget(window.lang_toggle)
    side.addLayout(brand)
    window.subtitle_label = QLabel()
    window.subtitle_label.setObjectName("appSubtitle")
    side.addWidget(window.subtitle_label)
    window.add_button = QPushButton()
    window.add_button.setObjectName("primaryButton")
    window.add_button.clicked.connect(window.add_videos)
    side.addWidget(window.add_button)
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setFrameShape(QFrame.NoFrame)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    settings = QWidget()
    settings_layout = QVBoxLayout(settings)
    settings_layout.setContentsMargins(0, 0, 2, 0)
    window._build_settings(settings_layout)
    settings_layout.addStretch()
    scroll.setWidget(settings)
    side.addWidget(scroll, 1)
    window.runtime_list = QListWidget()
    window.runtime_list.setObjectName("runtimeList")
    window.runtime_list.setFixedHeight(135)
    window.advanced_layout.addWidget(window.runtime_list)
    window.status_badge = QLabel()
    window.status_badge.setWordWrap(True)
    window.status_badge.setObjectName("statusBadge")
    side.addWidget(window.status_badge)

    content = QFrame()
    content.setObjectName("content")
    outer.addWidget(content, 1)
    layout = QVBoxLayout(content)
    layout.setContentsMargins(24, 24, 24, 16)
    layout.setSpacing(12)
    header = QHBoxLayout()
    titles = QVBoxLayout()
    window.heading_label = QLabel()
    window.heading_label.setObjectName("pageTitle")
    titles.addWidget(window.heading_label)
    window.caption_label = QLabel()
    window.caption_label.setObjectName("pageCaption")
    titles.addWidget(window.caption_label)
    header.addLayout(titles, 1)
    window.open_folder_button = QPushButton()
    window.open_folder_button.clicked.connect(window.open_output_folder)
    header.addWidget(window.open_folder_button)
    layout.addLayout(header)

    window.media_player = AudioReviewPlayer(window)
    window.media_player.follow_check.toggled.connect(lambda _checked: window._follow_position(window.media_player.player.position()))
    window.media_player.player.positionChanged.connect(window._follow_position)
    layout.addWidget(window.media_player)
    workspace = QSplitter(Qt.Vertical)
    workspace.setChildrenCollapsible(False)
    queue = QWidget()
    queue_layout = QVBoxLayout(queue)
    queue_layout.setContentsMargins(0, 0, 0, 0)
    window._build_queue(queue_layout)
    queue.setMaximumHeight(180)
    queue.setMinimumHeight(128)
    workspace.addWidget(queue)
    editor = QWidget()
    editor_layout = QVBoxLayout(editor)
    editor_layout.setContentsMargins(0, 0, 0, 0)
    window._build_preview(editor_layout)
    workspace.addWidget(editor)
    workspace.setSizes([125, 500])
    layout.addWidget(workspace, 1)

    window.details_tabs = QTabWidget()
    window.details_tabs.setMaximumHeight(170)
    logs = QWidget()
    logs_layout = QVBoxLayout(logs)
    logs_layout.setContentsMargins(0, 8, 0, 0)
    window.log_title = QLabel()
    window.log_title.hide()
    window.log = QPlainTextEdit()
    window.log.setReadOnly(True)
    window.log.setMaximumBlockCount(2000)
    logs_layout.addWidget(window.log)
    window.details_tabs.addTab(logs, "")
    history = QWidget()
    history_layout = QVBoxLayout(history)
    history_layout.setContentsMargins(0, 8, 0, 0)
    row = QHBoxLayout()
    window.history_label = QLabel()
    row.addWidget(window.history_label, 1)
    window.history_load_btn = QPushButton()
    window.history_load_btn.clicked.connect(window._load_selected_history)
    row.addWidget(window.history_load_btn)
    window.history_clear_btn = QPushButton()
    window.history_clear_btn.clicked.connect(window._clear_history)
    row.addWidget(window.history_clear_btn)
    history_layout.addLayout(row)
    window.history_list = QListWidget()
    window.history_list.itemDoubleClicked.connect(window._load_selected_history)
    history_layout.addWidget(window.history_list)
    window.details_tabs.addTab(history, "")
    window.details_tabs.setVisible(False)
    layout.addWidget(window.details_tabs)

    footer = QHBoxLayout()
    window.progress = QProgressBar()
    window.progress.setRange(0, 100)
    window.progress.setValue(0)
    footer.addWidget(window.progress, 1)
    window.start_button = QPushButton()
    window.start_button.setObjectName("primaryButton")
    window.start_button.clicked.connect(window.start_jobs)
    footer.addWidget(window.start_button)
    window.cancel_button = QPushButton()
    window.cancel_button.setEnabled(False)
    window.cancel_button.clicked.connect(window.cancel_all)
    footer.addWidget(window.cancel_button)
    window.skip_button = QPushButton()
    window.skip_button.setEnabled(False)
    window.skip_button.setVisible(False)
    window.skip_button.clicked.connect(window.skip_current)
    footer.addWidget(window.skip_button)
    window.burn_button = QPushButton()
    window.burn_button.clicked.connect(window.burn_subtitles)
    footer.addWidget(window.burn_button)
    window.details_button = QToolButton()
    window.details_button.setCheckable(True)
    window.details_button.setIcon(window.style().standardIcon(QStyle.SP_FileDialogDetailedView))
    window.details_button.toggled.connect(window.details_tabs.setVisible)
    footer.addWidget(window.details_button)
    layout.addLayout(footer)
    icons = {
        window.add_button: QStyle.SP_FileDialogNewFolder,
        window.start_button: QStyle.SP_MediaPlay,
        window.cancel_button: QStyle.SP_MediaStop,
        window.skip_button: QStyle.SP_MediaSkipForward,
        window.open_folder_button: QStyle.SP_DirOpenIcon,
        window.output_browse_button: QStyle.SP_DirOpenIcon,
        window.save_preview_btn: QStyle.SP_DialogSaveButton,
        window.copy_button: QStyle.SP_FileIcon,
        window.remove_button: QStyle.SP_TrashIcon,
        window.clear_button: QStyle.SP_DialogResetButton,
    }
    for button, icon in icons.items():
        color = "#ffffff" if button in (window.add_button, window.start_button) else "#356b5a"
        button.setIcon(tool_icon(window.style(), icon, color))

def build_settings(window, layout: QVBoxLayout) -> None:
    window.settings_group = QGroupBox()
    form = QVBoxLayout(window.settings_group)
    form.setContentsMargins(0, 12, 0, 0)
    form.setSpacing(8)
    layout.addWidget(window.settings_group)
    window.mode_label = QLabel()
    window.mode_combo = QComboBox()
    for key, display in MODES:
        window.mode_combo.addItem(display, key)
    form.addWidget(window.mode_label)
    form.addWidget(window.mode_combo)
    window.allow_cloud_check = QCheckBox()
    form.addWidget(window.allow_cloud_check)
    grid = QGridLayout()
    window.language_label = QLabel()
    window.language_combo = QComboBox()
    for name, code in LANGUAGES:
        label = name if not code else f"{name} ({code})"
        window.language_to_code[label] = code
        window.language_combo.addItem(label)
    window.model_label = QLabel()
    window.model_combo = QComboBox()
    window.model_combo.addItems(["tiny", "base", "small", "medium", "large-v3", "turbo"])
    window.model_combo.setCurrentText("small")
    grid.addWidget(window.language_label, 0, 0)
    grid.addWidget(window.model_label, 0, 1)
    grid.addWidget(window.language_combo, 1, 0)
    grid.addWidget(window.model_combo, 1, 1)
    window.output_label = QLabel()
    window.output_combo = QComboBox()
    window.output_combo.addItems(OUTPUT_FORMATS)
    window.channel_label = QLabel()
    window.channel_combo = QComboBox()
    for code in ("mix", "left", "right"):
        window.channel_combo.addItem(code, code)
    grid.addWidget(window.output_label, 2, 0)
    grid.addWidget(window.channel_label, 2, 1)
    grid.addWidget(window.output_combo, 3, 0)
    grid.addWidget(window.channel_combo, 3, 1)
    grid.setColumnStretch(0, 1)
    grid.setColumnStretch(1, 1)
    form.addLayout(grid)
    window.model_hint = QLabel()
    window.model_hint.setWordWrap(True)
    window.model_hint.setObjectName("modelHint")
    form.addWidget(window.model_hint)
    window.enhance_check = QCheckBox()
    window.terms_label = QLabel()
    window.terms_edit = QPlainTextEdit()
    window.terms_edit.setFixedHeight(70)
    window.custom_label = QLabel()
    window.custom_language = QLineEdit()
    form.addWidget(window.custom_label)
    form.addWidget(window.custom_language)
    window.advanced_button = QToolButton()
    window.advanced_button.setCheckable(True)
    window.advanced_button.setToolButtonStyle(Qt.ToolButtonTextBesideIcon)
    window.advanced_button.setArrowType(Qt.RightArrow)
    form.addWidget(window.advanced_button)
    window.advanced_widget = QWidget()
    window.advanced_layout = QVBoxLayout(window.advanced_widget)
    window.advanced_layout.setContentsMargins(0, 4, 0, 0)
    window.advanced_layout.addWidget(window.enhance_check)
    window.advanced_layout.addWidget(window.terms_label)
    window.advanced_layout.addWidget(window.terms_edit)
    window.format_label = QLabel()
    window.format_combo = QComboBox()
    window.format_combo.addItems(VIDEO_FILTERS)
    window.advanced_layout.addWidget(window.format_label)
    window.advanced_layout.addWidget(window.format_combo)
    window.folder_label = QLabel()
    window.output_dir = QLineEdit(str(APP_DIR / "outputs"))
    window.output_browse_button = QToolButton()
    window.output_browse_button.clicked.connect(window.choose_output_dir)
    folder = QHBoxLayout()
    folder.addWidget(window.output_dir, 1)
    folder.addWidget(window.output_browse_button)
    window.advanced_layout.addWidget(window.folder_label)
    window.advanced_layout.addLayout(folder)
    from model_storage import model_root
    window.model_location_label = QLabel()
    window.model_location = QLineEdit(str(model_root()))
    window.model_location.setReadOnly(True)
    window.model_location.setToolTip(str(model_root()))
    window.advanced_layout.addWidget(window.model_location_label)
    window.advanced_layout.addWidget(window.model_location)
    window.task_label = QLabel()
    window.transcribe_radio = QRadioButton()
    window.translate_radio = QRadioButton()
    window.transcribe_radio.setChecked(True)
    window.task_group = QButtonGroup(window)
    window.task_group.addButton(window.transcribe_radio)
    window.task_group.addButton(window.translate_radio)
    tasks = QHBoxLayout()
    tasks.addWidget(window.transcribe_radio)
    tasks.addWidget(window.translate_radio)
    window.advanced_layout.addWidget(window.task_label)
    window.advanced_layout.addLayout(tasks)
    window.parallel_label = QLabel()
    window.parallel_spin = QSpinBox()
    window.parallel_spin.setRange(1, 4)
    window.parallel_spin.valueChanged.connect(window._on_parallel_changed)
    window.advanced_layout.addWidget(window.parallel_label)
    window.advanced_layout.addWidget(window.parallel_spin)
    form.addWidget(window.advanced_widget)
    window.advanced_widget.hide()
    window.advanced_button.toggled.connect(window.advanced_widget.setVisible)
    window.advanced_button.toggled.connect(lambda checked: window.advanced_button.setArrowType(Qt.DownArrow if checked else Qt.RightArrow))
    window.mode_combo.currentIndexChanged.connect(window._on_mode_changed)
    window.language_combo.currentTextChanged.connect(window._toggle_custom_language)
    window.language_combo.currentTextChanged.connect(window.refresh_outputs)
    window.custom_language.textChanged.connect(window.refresh_outputs)
    window.output_combo.currentTextChanged.connect(window.refresh_outputs)
    window.output_dir.textChanged.connect(window.refresh_outputs)
    window.model_combo.currentTextChanged.connect(window._update_model_hint)
    window._toggle_custom_language()
    window._on_mode_changed()
    for combo in window.settings_group.findChildren(QComboBox):
        combo.setSizeAdjustPolicy(QComboBox.AdjustToMinimumContentsLengthWithIcon)
        combo.setMinimumContentsLength(4)
        combo.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Fixed)

def build_queue(window, layout: QVBoxLayout) -> None:
    queue_header = QHBoxLayout()
    window.queue_label = QLabel()
    window.queue_label.setObjectName("sectionTitle")
    queue_header.addWidget(window.queue_label)
    queue_header.addStretch(1)

    window.remove_button = QPushButton()
    window.remove_button.clicked.connect(window.remove_selected)
    queue_header.addWidget(window.remove_button)

    window.clear_button = QPushButton()
    window.clear_button.clicked.connect(window.clear_queue)
    queue_header.addWidget(window.clear_button)
    layout.addLayout(queue_header)

    window.table = QTableWidget(0, 5)
    window.table.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeToContents)
    window.table.horizontalHeader().setSectionResizeMode(1, QHeaderView.Stretch)
    window.table.horizontalHeader().setSectionResizeMode(2, QHeaderView.ResizeToContents)
    window.table.horizontalHeader().setSectionResizeMode(3, QHeaderView.Stretch)
    window.table.horizontalHeader().setSectionResizeMode(4, QHeaderView.ResizeToContents)
    window.table.setColumnHidden(3, True)
    window.table.verticalHeader().setDefaultSectionSize(38)
    window.table.verticalHeader().setVisible(False)
    window.table.setSelectionBehavior(QTableWidget.SelectRows)
    window.table.setAlternatingRowColors(False)
    window.table.setShowGrid(False)
    window.table.setEditTriggers(QTableWidget.NoEditTriggers)
    window.table.itemSelectionChanged.connect(window.preview_selected_output)
    window.table.itemDoubleClicked.connect(lambda _item: window.open_selected_output())
    layout.addWidget(window.table, 1)

def build_preview(window, layout: QVBoxLayout) -> None:
    title_row = QHBoxLayout()
    title_row.setSpacing(6)
    window.preview_title = QLabel()
    window.preview_title.setObjectName("sectionTitle")
    title_row.addWidget(window.preview_title)
    window.view_tabs = QTabBar()
    window.view_tabs.setObjectName("viewTabs")
    window.view_tabs.addTab("")
    window.view_tabs.addTab("")
    window.view_tabs.setExpanding(False)
    window.view_tabs.setDrawBase(False)
    title_row.addWidget(window.view_tabs)
    title_row.addStretch(1)
    window.save_preview_btn = QPushButton()
    window.save_preview_btn.clicked.connect(window._save_preview)
    title_row.addWidget(window.save_preview_btn)
    window.copy_button = QPushButton()
    window.copy_button.clicked.connect(window.copy_preview)
    title_row.addWidget(window.copy_button)
    layout.addLayout(title_row)

    window.review_button = QPushButton()
    window.review_button.setCheckable(True)
    title_row.addWidget(window.review_button)
    window.reading_button = QToolButton()
    window.reading_button.setIcon(tool_icon(window.style(), QStyle.SP_FileDialogDetailedView))
    window.reading_button.setPopupMode(QToolButton.InstantPopup)
    menu = QMenu(window.reading_button)
    menu.addAction(window.shortcuts["find"])
    menu.addAction(window.shortcuts["replace"])
    menu.addSeparator()
    window.open_result_action = menu.addAction(tool_icon(window.style(), QStyle.SP_FileIcon), "", window.open_selected_output)
    window.reading_export_action = menu.addAction(tool_icon(window.style(), QStyle.SP_DialogSaveButton), "", window.export_reading_copy)
    window.copy_original_action = menu.addAction("", lambda: QApplication.clipboard().setText(window.preview.toPlainText()))
    menu.addSeparator()
    window.recovery_action = menu.addAction("", window._offer_recovery)
    window.reading_button.setMenu(menu)
    title_row.addWidget(window.reading_button)
    for button in (window.save_preview_btn, window.copy_button, window.reading_button):
        button.setFixedSize(34, 34)
        button.setObjectName("iconButton")
    window.review_button.setMinimumWidth(88)
    window.review_list = QListWidget()
    window.review_list.setObjectName("reviewList")
    window.review_list.setMaximumHeight(120)
    window.review_list.itemClicked.connect(window._seek_review_item)
    window.review_list.itemActivated.connect(window._seek_review_item)
    window.review_list.setTextElideMode(Qt.ElideRight)
    window.review_button.toggled.connect(window.review_list.setVisible)
    layout.addWidget(window.review_list)
    window.review_list.hide()
    window.preview = TranscriptEdit()
    window.preview.setObjectName("transcriptEditor")
    window.preview.setReadOnly(True)
    window.timestamp_highlighter = TimestampHighlighter(window.preview.document())
    window.preview.seekRequested.connect(window.media_player.seek)
    window.save_preview_btn.setEnabled(False)
    window.preview.setSizePolicy(QSizePolicy.Expanding, QSizePolicy.Expanding)
    window.reading_view = QPlainTextEdit()
    window.reading_view.setReadOnly(True)
    window.reading_view.setObjectName("readingView")
    window.editor_stack = QStackedWidget()
    window.editor_stack.addWidget(window.preview)
    window.editor_stack.addWidget(window.reading_view)
    window._build_find_bar(layout)
    layout.addWidget(window.editor_stack, 1)
    window.reading_timer = QTimer(window)
    window.reading_timer.setSingleShot(True)
    window.reading_timer.setInterval(120)
    window.reading_timer.timeout.connect(window._update_reading_view)
    window.preview.textChanged.connect(window._preview_text_changed)
    window.view_tabs.currentChanged.connect(window._change_view)

def build_find_bar(window, layout: QVBoxLayout) -> None:
    window.find_bar = QFrame()
    window.find_bar.setObjectName("findBar")
    rows = QVBoxLayout(window.find_bar)
    rows.setContentsMargins(8, 6, 8, 6)
    rows.setSpacing(6)
    top = QHBoxLayout()
    window.find_input = QLineEdit()
    window.find_input.setClearButtonEnabled(True)
    window.find_input.returnPressed.connect(window.find_text)
    top.addWidget(window.find_input, 1)
    window.find_previous = QToolButton()
    window.find_previous.setIcon(tool_icon(window.style(), QStyle.SP_ArrowUp))
    window.find_previous.clicked.connect(lambda: window.find_text(backward=True))
    top.addWidget(window.find_previous)
    window.find_next = QToolButton()
    window.find_next.setIcon(tool_icon(window.style(), QStyle.SP_ArrowDown))
    window.find_next.clicked.connect(lambda: window.find_text())
    top.addWidget(window.find_next)
    window.find_close = QToolButton()
    window.find_close.setIcon(tool_icon(window.style(), QStyle.SP_DialogCloseButton))
    window.find_close.clicked.connect(window.hide_find)
    top.addWidget(window.find_close)
    rows.addLayout(top)
    window.replace_row = QWidget()
    bottom = QHBoxLayout(window.replace_row)
    bottom.setContentsMargins(0, 0, 0, 0)
    window.replace_input = QLineEdit()
    bottom.addWidget(window.replace_input, 1)
    window.replace_button = QPushButton()
    window.replace_button.clicked.connect(window.replace_current)
    bottom.addWidget(window.replace_button)
    window.replace_all_button = QPushButton()
    window.replace_all_button.clicked.connect(window.replace_all)
    bottom.addWidget(window.replace_all_button)
    rows.addWidget(window.replace_row)
    for button in (window.find_previous, window.find_next, window.find_close):
        button.setObjectName("iconButton")
        button.setFixedSize(30, 30)
    escape = QAction(window.find_bar)
    escape.setShortcut(QKeySequence("Escape"))
    escape.setShortcutContext(Qt.WidgetWithChildrenShortcut)
    escape.triggered.connect(window.hide_find)
    window.find_bar.addAction(escape)
    layout.addWidget(window.find_bar)
    window.find_bar.hide()
